#!/usr/bin/env python3
"""Generate ``gopro_camera/spec_tables.py`` from the official Open GoPro HTTP spec.

The driver must never hardcode setting/status IDs or option values from memory. This script reads
the official OpenAPI document published at https://gopro.github.io/OpenGoPro/http/openapi.json
(or a local copy) and emits a pure-data Python module with:

- every setting ID, its title, its options (ID -> display label) and, per option, the camera
  models the spec says support it;
- every status ID and its title;
- the list of supported cameras.

Usage:
    python3 scripts/generate_spec_tables.py [--spec PATH_OR_URL] [--out PATH]
"""

from __future__ import annotations

import argparse
import datetime
import json
import pprint
import re
import urllib.request
from pathlib import Path
from typing import Any

DEFAULT_SPEC_URL = "https://gopro.github.io/OpenGoPro/http/openapi.json"
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "gopro_camera" / "spec_tables.py"

# The minimum firmware table is not part of the OpenAPI document; it is published in the BLE spec
# ("Supported Cameras", https://gopro.github.io/OpenGoPro/ble). Update it here when the spec changes.
MIN_FIRMWARE = {
    "MISSION 1": "v01.10.00",
    "MISSION 1 Pro": "v01.10.00",
    "LIT HERO": "v01.10.00",
    "MAX 2": "v01.10.00",
    "HERO13 Black": "v01.10.00",
    "HERO12 Black": "v01.10.00",
    "HERO11 Black Mini": "v01.10.00",
    "HERO11 Black": "v01.10.00",
    "HERO10 Black": "v01.10.00",
    "HERO9 Black": "v01.70.00",
}


def _load(spec: str) -> dict[str, Any]:
    if re.match(r"^https?://", spec):
        with urllib.request.urlopen(spec, timeout=30) as resp:
            return json.load(resp)
    return json.loads(Path(spec).read_text())


def _snake(title: str) -> str:
    name = title.lower().replace("-", " ").replace("/", " ")
    name = re.sub(r"[^a-z0-9 ]", "", name)
    name = re.sub(r"\s+", "_", name.strip())
    if name[0].isdigit():
        name = "n" + name
    return name


def _strip_md(text: str) -> str:
    return re.sub(r"\*\*", "", text.split("\n")[0]).strip()


def build_tables(spec: dict[str, Any]) -> dict[str, Any]:
    settings: dict[int, dict[str, Any]] = {}
    for path, ops in spec["paths"].items():
        m = re.match(r"^/gopro/camera/setting\?setting=(\d+)$", path)
        if not m:
            continue
        op = ops["get"]
        sid = int(m.group(1))
        option_param = next(p for p in op["parameters"] if p["name"] == "option")
        schema = option_param["schema"]
        labels = {int(k): v for k, v in schema.get("x-enumDescriptions", {}).items()}
        option_cameras = {int(k): list(v) for k, v in schema.get("x-option-metadata", {}).items()}
        description = (schema.get("description") or "").strip().split("\n")[0]
        # Non-enumerated settings (e.g. a percentage) only carry a free-text range in their description.
        value_range = None
        if not schema.get("enum") and (rm := re.search(r"(\d+)\s*-\s*(\d+)", description)):
            value_range = (int(rm.group(1)), int(rm.group(2)))
        settings[sid] = {
            "name": _snake(schema.get("title") or op["summary"].rsplit("(", 1)[0]),
            "title": schema.get("title") or op["summary"],
            "description": description,
            "options": {int(o): labels.get(int(o), str(o)) for o in schema.get("enum", [])},
            "range": value_range,
            "option_cameras": option_cameras,
            "cameras": list(op.get("x-supported-cameras", [])),
        }
    statuses: dict[int, str] = {}
    status_values: dict[int, dict[int, str]] = {}
    for key, value in spec["components"]["schemas"]["State"]["properties"]["status"]["properties"].items():
        desc = value.get("description", "") or value.get("title", key)
        statuses[int(key)] = _strip_md(desc)
        # Enumerated statuses document their values as a markdown table: | Value | Meaning |
        rows = re.findall(r"^\|\s*(-?\d+)\s*\|\s*([^|]*?)\s*\|", desc, flags=re.M)
        if rows:
            status_values[int(key)] = {int(v): m for v, m in rows}
    cameras = [c["name"] for c in spec.get("x-all-cameras", [])]
    webcam: dict[str, dict[int, str]] = {}
    for param in spec["paths"]["/gopro/webcam/start"]["get"]["parameters"]:
        rows = re.findall(r"^\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|", param.get("description", ""), flags=re.M)
        if rows:
            webcam[param["name"]] = {int(v): label for v, label in rows}
    return {
        "webcam": webcam,
        "settings": dict(sorted(settings.items())),
        "statuses": dict(sorted(statuses.items())),
        "status_values": dict(sorted(status_values.items())),
        "cameras": cameras,
    }


def render(tables: dict[str, Any], source: str, spec_version: str) -> str:
    header = f'''"""Open GoPro spec tables. AUTO-GENERATED by scripts/generate_spec_tables.py - do not edit by hand.

Source: {source}
Spec version: {spec_version}
Generated: {datetime.date.today().isoformat()}
"""

from typing import Any, Final

SPEC_VERSION: Final[str] = {spec_version!r}
'''
    body = [
        "SETTINGS: Final[dict[int, dict[str, Any]]] = "
        + pprint.pformat(tables["settings"], width=110, sort_dicts=False),
        "STATUSES: Final[dict[int, str]] = " + pprint.pformat(tables["statuses"], width=110, sort_dicts=False),
        "STATUS_VALUES: Final[dict[int, dict[int, str]]] = "
        + pprint.pformat(tables["status_values"], width=110, sort_dicts=False),
        "WEBCAM_PARAMS: Final[dict[str, dict[int, str]]] = " + pprint.pformat(tables["webcam"], width=110),
        "CAMERAS: Final[list[str]] = " + pprint.pformat(tables["cameras"], width=110),
        "MIN_FIRMWARE: Final[dict[str, str]] = " + pprint.pformat(MIN_FIRMWARE, width=110, sort_dicts=False),
    ]
    return header + "\n" + "\n\n".join(body) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", default=DEFAULT_SPEC_URL, help="OpenAPI JSON path or URL")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    spec = _load(args.spec)
    tables = build_tables(spec)
    args.out.write_text(render(tables, DEFAULT_SPEC_URL, spec["info"].get("version", "unknown")))
    print(f"Wrote {len(tables['settings'])} settings, {len(tables['statuses'])} statuses to {args.out}")


if __name__ == "__main__":
    main()
